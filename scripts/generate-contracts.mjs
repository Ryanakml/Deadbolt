import fs from "node:fs";
const data = Object.fromEntries(
  fs
    .readdirSync("contracts/manifest")
    .filter((x) => x.endsWith(".json"))
    .sort()
    .map((x) => [
      x,
      JSON.parse(fs.readFileSync(`contracts/manifest/${x}`, "utf8")),
    ]),
);
data["worker/protocol.schema.json"] = JSON.parse(
  fs.readFileSync("contracts/worker/protocol.schema.json", "utf8"),
);
const text = `// Generated by scripts/generate-contracts.mjs. Do not edit.
import type { JSONValue } from './json.js';
export const schemas: Record<string, JSONValue> = ${JSON.stringify(data, null, 2)};
`;
const path = "sdk/typescript/src/schema-data.ts";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(path, "utf8") !== text)
    throw Error("Generated schemas are stale");
} else fs.writeFileSync(path, text);
const enums = JSON.parse(
  fs.readFileSync("contracts/common/enums.json", "utf8"),
);
let ts = "// Generated by scripts/generate-contracts.mjs. Do not edit.\n";
let go =
  "// Code generated by scripts/generate-contracts.mjs; DO NOT EDIT.\npackage contracts\n";
for (const [name, values] of Object.entries(enums)) {
  ts += `export const ${name} = ${JSON.stringify(values)} as const;\nexport type ${name} = typeof ${name}[number];\n`;
  go += `type ${name} string\nconst (\n${values.map((v) => `${name}${v} ${name} = ${JSON.stringify(v)}`).join("\n")}\n)\n`;
}
const { execFileSync } = await import("node:child_process");
go = execFileSync("gofmt", [], { input: go, encoding: "utf8" });
for (const [path, text] of [
  ["sdk/typescript/src/enums.ts", ts],
  ["internal/contracts/enums_generated.go", go],
]) {
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(path, "utf8") !== text)
      throw Error(`Generated enums are stale: ${path}`);
  } else fs.writeFileSync(path, text);
}
